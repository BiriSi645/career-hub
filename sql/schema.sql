-- Career Hub PostgreSQL schema (19 normalized tables)

CREATE TABLE ROLES (
  ID SERIAL PRIMARY KEY, NAME VARCHAR(30) NOT NULL UNIQUE, DESCRIPTION VARCHAR(255)
);


CREATE TABLE USERS (
  ID SERIAL PRIMARY KEY, EMAIL VARCHAR(255) NOT NULL UNIQUE, PASSWORD_HASH VARCHAR(255) NOT NULL,
  FIRST_NAME VARCHAR(80) NOT NULL,
  LAST_NAME VARCHAR(80) NOT NULL,
  PHONE VARCHAR(30),
  IS_ACTIVE_ACCOUNT BOOLEAN NOT NULL DEFAULT TRUE,
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE TABLE USER_ROLES
(
  USER_ID INTEGER REFERENCES USERS (ID) ON DELETE CASCADE,
  ROLE_ID INTEGER REFERENCES ROLES (ID) ON DELETE RESTRICT,
  ASSIGNED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (
    USER_ID,
    ROLE_ID
  )
);


CREATE TABLE JOBSEEKER_PROFILES
(
  USER_ID INTEGER PRIMARY KEY REFERENCES USERS (ID) ON DELETE CASCADE,
  HEADLINE VARCHAR(160),
  BIO TEXT,
  CITY VARCHAR(100),
  COUNTRY VARCHAR(100),
  LINKEDIN_URL VARCHAR(255),
  PORTFOLIO_URL VARCHAR(255),
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE TABLE COMPANIES (
  ID SERIAL PRIMARY KEY, NAME VARCHAR(160) NOT NULL UNIQUE, DESCRIPTION TEXT, WEBSITE VARCHAR(255),
  INDUSTRY VARCHAR(120),
  CITY VARCHAR(100),
  COUNTRY VARCHAR(100) NOT NULL DEFAULT 'Türkiye',
  IS_VERIFIED BOOLEAN NOT NULL DEFAULT FALSE,
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE TABLE COMPANY_STAFF
(
  ID SERIAL PRIMARY KEY,
  COMPANY_ID INTEGER NOT NULL REFERENCES COMPANIES (ID) ON DELETE CASCADE,
  USER_ID INTEGER NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
  TITLE VARCHAR(100),
  CAN_MANAGE_COMPANY BOOLEAN NOT NULL DEFAULT FALSE,
  JOINED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (
    COMPANY_ID,

    USER_ID
  )
);


CREATE TABLE SKILLS (ID SERIAL PRIMARY KEY, NAME VARCHAR(80) NOT NULL UNIQUE, CATEGORY VARCHAR(80));


CREATE TABLE USER_SKILLS
(
  USER_ID INTEGER REFERENCES USERS (ID) ON DELETE CASCADE,
  SKILL_ID INTEGER REFERENCES SKILLS (ID) ON DELETE CASCADE,
  PROFICIENCY VARCHAR(20) NOT NULL DEFAULT 'intermediate' CHECK (PROFICIENCY IN (
    'beginner',

    'intermediate',
    'advanced',
    'expert'
  )),
  YEARS_EXPERIENCE NUMERIC(
    4,

    1
  ) NOT NULL DEFAULT 0 CHECK (YEARS_EXPERIENCE >= 0
  ),
  PRIMARY KEY (
    USER_ID,
    SKILL_ID
  )
);


CREATE TABLE EDUCATIONS
(
  ID SERIAL PRIMARY KEY,
  USER_ID INTEGER NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
  INSTITUTION VARCHAR(180) NOT NULL,
  DEGREE VARCHAR(120) NOT NULL,
  FIELD_OF_STUDY VARCHAR(120),
  START_DATE DATE NOT NULL,
  END_DATE DATE, DESCRIPTION TEXT, CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    END_DATE IS NULL
    OR END_DATE >= START_DATE
  )
);


CREATE TABLE EXPERIENCES
(
  ID SERIAL PRIMARY KEY,
  USER_ID INTEGER NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
  COMPANY_ID INTEGER REFERENCES COMPANIES (ID) ON DELETE SET NULL,
  COMPANY_NAME VARCHAR(160) NOT NULL,
  TITLE VARCHAR(120) NOT NULL,
  LOCATION VARCHAR(120),
  START_DATE DATE NOT NULL,
  END_DATE DATE, DESCRIPTION TEXT, CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    END_DATE IS NULL
    OR END_DATE >= START_DATE
  )
);

CREATE INDEX IX_EXPERIENCES_COMPANY_ID ON EXPERIENCES (COMPANY_ID);


CREATE TABLE RESUMES
(
  ID SERIAL PRIMARY KEY,
  USER_ID INTEGER NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
  TITLE VARCHAR(120) NOT NULL,
  FILE_URL VARCHAR(500) NOT NULL,
  IS_PRIMARY BOOLEAN NOT NULL DEFAULT FALSE,
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE TABLE JOB_CATEGORIES (
  ID SERIAL PRIMARY KEY, NAME VARCHAR(100) NOT NULL UNIQUE, DESCRIPTION VARCHAR(255)
);


CREATE TABLE JOB_POSTINGS
(
  ID SERIAL PRIMARY KEY,
  COMPANY_ID INTEGER NOT NULL REFERENCES COMPANIES (ID) ON DELETE CASCADE,
  CATEGORY_ID INTEGER NOT NULL REFERENCES JOB_CATEGORIES (ID) ON DELETE RESTRICT,
  CREATED_BY INTEGER NOT NULL REFERENCES USERS (ID) ON DELETE RESTRICT,
  TITLE VARCHAR(160) NOT NULL,
  DESCRIPTION TEXT NOT NULL,
  REQUIREMENTS TEXT, LOCATION VARCHAR(120) NOT NULL,
  EMPLOYMENT_TYPE VARCHAR(30) NOT NULL CHECK (EMPLOYMENT_TYPE IN (
    'full_time',

    'part_time',
    'internship',
    'contract'
  )),
  WORKPLACE_TYPE VARCHAR(20) NOT NULL DEFAULT 'onsite' CHECK (WORKPLACE_TYPE IN (
    'onsite',

    'hybrid',
    'remote'
  )),
  SALARY_MIN NUMERIC(
    12,

    2
  ),
  SALARY_MAX NUMERIC(
    12,

    2
  ),
  STATUS VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (STATUS IN (
    'draft',

    'open',
    'closed',
    'rejected'
  )),
  DEADLINE DATE, CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    SALARY_MIN IS NULL
    OR SALARY_MAX IS NULL
    OR SALARY_MAX >= SALARY_MIN
  )
);


CREATE TABLE JOB_REQUIRED_SKILLS
(
  JOB_ID INTEGER REFERENCES JOB_POSTINGS (ID) ON DELETE CASCADE,
  SKILL_ID INTEGER REFERENCES SKILLS (ID) ON DELETE CASCADE,
  IS_MANDATORY BOOLEAN NOT NULL DEFAULT TRUE,
  MINIMUM_PROFICIENCY VARCHAR(20) NOT NULL DEFAULT 'intermediate' CHECK (MINIMUM_PROFICIENCY IN (
    'beginner',

    'intermediate',
    'advanced',
    'expert'
  )),
  PRIMARY KEY (
    JOB_ID,
    SKILL_ID
  )
);


CREATE TABLE APPLICATIONS
(
  ID SERIAL PRIMARY KEY,
  JOB_ID INTEGER NOT NULL REFERENCES JOB_POSTINGS (ID) ON DELETE CASCADE,
  APPLICANT_ID INTEGER NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
  RESUME_ID INTEGER REFERENCES RESUMES (ID) ON DELETE
  SET NULL, COVER_LETTER TEXT, STATUS VARCHAR(20) NOT NULL DEFAULT 'submitted' CHECK (STATUS IN (
    'submitted',

    'reviewing',
    'shortlisted',
    'interview', 'offered',
    'hired', 'rejected',
    'withdrawn'
  )),
  APPLIED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (
    JOB_ID,

    APPLICANT_ID
  )
);


CREATE TABLE APPLICATION_STATUS_HISTORY
(
  ID SERIAL PRIMARY KEY,
  APPLICATION_ID INTEGER NOT NULL REFERENCES APPLICATIONS (ID) ON DELETE CASCADE,
  OLD_STATUS VARCHAR(20),
  NEW_STATUS VARCHAR(20) NOT NULL,
  CHANGED_BY INTEGER REFERENCES USERS (ID) ON DELETE
  SET NULL, NOTE VARCHAR(500), CHANGED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE TABLE SAVED_JOBS
(
  USER_ID INTEGER REFERENCES USERS (ID) ON DELETE CASCADE,
  JOB_ID INTEGER REFERENCES JOB_POSTINGS (ID) ON DELETE CASCADE,
  SAVED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (
    USER_ID,
    JOB_ID
  )
);


CREATE TABLE INTERVIEWS
(
  ID SERIAL PRIMARY KEY,
  APPLICATION_ID INTEGER NOT NULL REFERENCES APPLICATIONS (ID) ON DELETE CASCADE,
  SCHEDULED_BY INTEGER REFERENCES USERS (ID) ON DELETE
  SET NULL,
  SCHEDULED_AT TIMESTAMPTZ NOT NULL,
  INTERVIEW_TYPE VARCHAR(20) NOT NULL CHECK (INTERVIEW_TYPE IN (
    'phone',

    'video',
    'onsite'
  )), LOCATION_OR_LINK VARCHAR(500) NOT NULL,
  NOTES TEXT, STATUS VARCHAR(20) NOT NULL DEFAULT 'scheduled' CHECK (STATUS IN (
    'scheduled',

    'completed',
    'cancelled'
  )),
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE TABLE NOTIFICATIONS
(
  ID SERIAL PRIMARY KEY,
  USER_ID INTEGER NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
  TITLE VARCHAR(160) NOT NULL,
  MESSAGE TEXT NOT NULL,
  LINK VARCHAR(500),
  IS_READ BOOLEAN NOT NULL DEFAULT FALSE,
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now()
);


CREATE INDEX IX_JOB_STATUS_DEADLINE ON JOB_POSTINGS (
  STATUS,
  DEADLINE
);

CREATE INDEX IX_APPLICATION_JOB_STATUS ON APPLICATIONS (
  JOB_ID,
  STATUS
);

CREATE INDEX IX_NOTIFICATIONS_USER_READ ON NOTIFICATIONS (
  USER_ID,
  IS_READ
);

CREATE INDEX IX_INTERVIEWS_SCHEDULED_AT ON INTERVIEWS (SCHEDULED_AT);
